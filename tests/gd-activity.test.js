'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const GD = require('../assets/js/gd-activity.js');
const date = '2026-10-20';
const stops = ['甲','乙','丙','丁'].map((station,index) => ({station,arrival:`10:${String(index*10).padStart(2,'0')}`,departure:`10:${String(index*10+1).padStart(2,'0')}`}));
const train = {trainNumber:'試9001',line:'試験線',startDate:'2026/03/16',stops};
const payload = states => ({serviceDate:date,status:'published',items:[{trainNumber:'試9001',stops:structuredClone(stops),baseState:'operate',timeChanged:false,
  edges:states.map((state,index) => ({start:stops[index].station,end:stops[index+1].station,state}))}]});
const before = JSON.stringify(train);
assert.equal(GD.project(train,payload(['hidden','hidden','hidden']),date).length, 0);
const partial = GD.project(train,payload(['operate','hidden','operate']),date);
assert.deepEqual(partial.map(row => row.stops.map(stop => stop.station)), [['甲','乙'],['丙','丁']], 'never bridge a suspended section');
const full = GD.project(train,payload(['operate','operate','operate']),date);
assert.equal(full.length, 1);
assert.deepEqual(full[0].stops.map(stop => stop.station), ['甲','乙','丙','丁']);
assert.equal(full[0].stops[1].arrival, '10:10');
assert.equal(full[0].stops[1].departure, '10:11');
assert.equal(full[0].gdDetailStops[0].arrival, '10:00', 'chart clipping must not erase arrival times in the detail table');
assert.equal(full[0].gdDetailStops.at(-1).departure, '10:31', 'detail table retains departure times at line boundaries');
assert.equal(full[0].stops[0].arrival, '');
assert.equal(full[0].stops.at(-1).departure, '');
const declared = payload(['operate','operate','operate']);
declared.items[0].sectionStart = '越後石山'; declared.items[0].sectionEnd = '大宮操';
declared.items[0].availableStart = '高崎'; declared.items[0].availableEnd = '大宮操';
const visible = GD.project({...train,origin:'※※※※',destination:'大宮操'},declared,date)[0];
assert.equal(GD.routeLabel(visible), '越後石山 ～ 大宮操（通達区間）');
assert.equal(visible.gdState, 'operate');
assert.equal(visible.origin, '※※※※', 'do not rewrite the original source metadata');
assert.equal(visible.gdAvailableStart, '高崎');
const cancellation = payload(['cancelled','prohibited','operate']);
cancellation.items[0].edges[0].cancelledAt = '2026-10-20T00:00:00Z';
cancellation.items[0].edges[0].previousStops = [{station:'甲',departure:'09:00'},{station:'乙',arrival:'09:10'}];
const current = GD.project(train,cancellation,date);
assert.equal(current[0].gdState, 'cancelled');
assert.equal(current[0].stops[0].departure, '09:00', 'red uses the last running timetable, not subsequently entered times');
assert.equal(current[1].gdState, 'prohibited');
assert.equal(current[2].gdState, 'operate');
assert.match(GD.styles.cancelled, /stroke:#c00000/);
assert.match(GD.styles.cancelled, /stroke-dasharray:none/);
assert.notEqual(GD.styles.prohibited, GD.styles.cancelled);
for (const state of ['operate','changed','prohibited','unknown']) assert.equal(GD.styles[state], '', 'only same-day cancellations get special styling');
const changed = payload(['operate','operate','operate']);
changed.items[0].timeChanged = true;
assert.equal(GD.project(train,changed,date)[0].gdState, 'changed');
changed.items[0].timeChanged = false;
changed.items[0].stops[0].departure = '12:00';
assert.equal(GD.project(train,changed,date)[0].gdState, 'operate', 'time difference must not force the time-change flag');
assert.equal(GD.project(train,changed,date)[0].stops[0].departure, '12:00');
assert.equal(JSON.stringify(train), before, 'projection is read-only');
assert.equal(GD.project({...train,source:'operation-service',operationServiceDate:'2026-10-21'},changed,date).length, 0);
assert.equal(GD.project({...train,source:'operation-service',operationServiceDate:date},{serviceDate:date,status:'withdrawn',items:[]},date).length, 0);
assert.throws(() => GD.project(train,null,date), /取得/);
assert.throws(() => GD.project(train,payload([]),'2026-10-21'), /取得/);
assert.equal(GD.project(train,{serviceDate:date,status:'legacy',items:[]},date)[0].gdState, 'operate', 'unmanaged source schedules remain available');
const unresolved = payload(['unknown','unknown','unknown']);
assert.equal(GD.project(train,unresolved,date)[0].gdState, 'unknown');
const html = fs.readFileSync('JREgyoumu/ATOSsys/GD/diagram.html','utf8');
assert.match(html, /GD\.project\(t,gdPayload,date,stationKey\)/);
assert.match(html, /style="\$\{GD\.styles\[t\.gdState\]/, 'inline stroke styles survive SVG cloning for PNG/PDF');
assert.match(html, /GD\.styles\[t\.gdState\]\?\?GD\.styles\.unknown/, 'an empty ordinary style must not fall back to unknown gray');
assert.match(html, /gdPayload\.serviceDate!==date/);
assert.match(html, /古い運転状態は表示しません/);
assert.match(html, /fetchGdActivity\(date\)/);
assert.doesNotMatch(html, /<div class="legend"|灰点線|紫破線|黄褐/);
console.log('GD activity projection: ok');
